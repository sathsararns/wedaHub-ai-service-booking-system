"""
LangChain tool wrappers around the AI service's external actions —
provider search, recommendation ranking, booking creation, and booking
status lookup. These are the tools an LLM actually chooses to call (see
app/graph/tool_agent.py), replacing the old direct Python calls that used
to live in search_node.py / recommendation_node.py / booking_create_node.py
/ booking_status_node.py.

No business logic is duplicated here — each tool is a thin wrapper
around the existing, already-tested implementation
(app/agents/search_agent.py, app/agents/recommendation_agent.py,
app/tools/booking_tool.py, app/services/booking_status_service.py).

=========================================================
Why the tool signatures look the way they do (anti-hallucination design)
=========================================================

search_providers takes `service` and `location` as LLM-supplied
arguments because those genuinely vary per search and come from the
user's own message — already extracted by requirement_node before this
ever runs, so the LLM is passing along known-real values, not inventing
them.

recommend_providers, create_booking and get_booking_status take NO
identity-bearing arguments from the LLM at all. provider_id and
booking_id are read from `context` — populated from state the LLM never
sees as a free-text field: provider_id via the existing index-based
"Book N" selection (booking_agent_node.py, unchanged), booking_id by
re-deriving it from this session's own booking_result. This mirrors the
pre-existing safe pattern in recommendation_node.py, which never trusted
an LLM's provider name for anything functional and always re-resolved
the real record by index — the same principle now applies to every tool
that touches a real record.

create_booking also re-validates every required field itself before
calling the backend, even though the graph nodes calling it already
gate on the same checks — defence in depth, so a prompt/model quirk
can never create an invalid booking.

=========================================================
Retrieval (RAG) — search_providers
=========================================================

search_providers now tries semantic retrieval first
(app.rag.provider_index.semantic_search): it embeds a query built from
`service`, `location`, and (if available) the customer's own raw
message, and returns the most semantically relevant REAL provider
records — not text generated by an LLM. If semantic retrieval is
unavailable (embedding model not loaded) or returns no result above its
relevance threshold, it falls back to the exact/regex
app.agents.search_agent path unchanged. Either way, `providers` in
`context` is always a list of real provider dicts from the backend —
recommend_providers (and its existing index-based anti-hallucination
mapping) doesn't need to know or care which retrieval path produced them.
"""

import logging

from langchain_core.tools import tool
from pydantic import BaseModel, Field

from app.agents.recommendation_agent import recommendation_agent
from app.agents.search_agent import search_agent
from app.models.requirements import Requirement
from app.rag.provider_index import semantic_search
from app.services.booking_status_service import get_booking_status as fetch_booking_status
from app.tools.booking_tool import BookingTool

logger = logging.getLogger(__name__)


class SearchProvidersInput(BaseModel):
    service: str = Field(description="Service category to search for, e.g. Electrician")
    location: str = Field(description="City/location to search in, e.g. Kandy")


def _extract_booking_id(booking_result):
    """
    booking_create_node.py stores a FLAT dict in state["booking_result"]
    (no nested "booking" key). Still checked defensively in case
    something ever produces the nested {"booking": {...}} shape instead.
    """
    if not isinstance(booking_result, dict):
        return None

    nested = booking_result.get("booking")
    if isinstance(nested, dict):
        nested_id = (
            nested.get("_id")
            or nested.get("bookingId")
            or nested.get("booking_id")
        )
        if nested_id:
            return nested_id

    return (
        booking_result.get("_id")
        or booking_result.get("booking_id")
        or booking_result.get("bookingId")
    )


def make_tools(context: dict, session_id: str = None):
    """
    Builds the 4 tools bound to this one request's mutable `context`
    dict. A fresh set is built per chat turn — nothing is shared across
    sessions or requests. Tools write their real, structured results into
    `context`; the calling graph node reads them from there afterwards.
    The LLM only ever sees the short text each tool returns — it is never
    asked to transcribe structured data itself.
    """

    @tool("search_providers", args_schema=SearchProvidersInput)
    def search_providers(service: str, location: str) -> str:
        """Search WedaHub's real provider database for a service in a location."""

        logger.info(
            "session=%s TOOL CALL search_providers(service=%r, location=%r)",
            session_id, service, location,
        )

        query = f"{service} in {location}".strip()
        user_input = context.get("user_input")
        if user_input:
            query = f"{query}. Customer request: {user_input}"

        retrieval_mode = "semantic"
        results = semantic_search(query)

        if results is None:
            # Embedding model unavailable — fall back to the exact/regex path.
            retrieval_mode = "keyword_fallback"
            requirement = Requirement(service=service, location=location)
            providers = search_agent(requirement)
        elif results:
            providers = [provider for provider, _score in results]
        else:
            # Semantic retrieval ran but nothing cleared the relevance
            # threshold — a real "no good match", not an unavailable index.
            providers = []

        context["providers"] = providers

        logger.info(
            "session=%s TOOL RESULT search_providers -> %d provider(s) via %s",
            session_id, len(providers), retrieval_mode,
        )

        if not providers:
            return f"No providers found for {service} in {location}."

        return (
            f"Found {len(providers)} provider(s) for {service} in {location} "
            f"(retrieval={retrieval_mode})."
        )

    @tool("recommend_providers")
    def recommend_providers() -> str:
        """
        Rank the providers search_providers just found and select the
        best matches. Only call this after search_providers has run in
        this turn and found at least one provider.
        """

        providers = context.get("providers") or []

        logger.info(
            "session=%s TOOL CALL recommend_providers (providers_available=%d)",
            session_id, len(providers),
        )

        if not providers:
            context["recommendations"] = {"recommendations": []}
            context["recommended_providers"] = []
            return "No providers available to rank — call search_providers first."

        result = recommendation_agent.invoke(
            {
                "requirements": context.get("requirements", {}),
                "providers": providers,
            }
        )

        recommended = []
        for item in result.recommendations:
            if item.provider_index >= len(providers):
                continue

            provider = providers[item.provider_index]
            recommended.append(
                {
                    "provider_index": item.provider_index,
                    "provider_id": provider.get("_id"),
                    "provider_name": (
                        provider.get("businessName")
                        or (
                            provider.get("firstName", "")
                            + " "
                            + provider.get("lastName", "")
                        ).strip()
                    ),
                }
            )

        context["recommendations"] = result.model_dump()
        context["recommended_providers"] = recommended

        logger.info(
            "session=%s TOOL RESULT recommend_providers -> ranked %d of %d",
            session_id, len(recommended), len(providers),
        )

        return f"Ranked and selected {len(recommended)} provider(s)."

    @tool("create_booking")
    def create_booking() -> str:
        """
        Create the booking using the provider, service, city, date and
        description already confirmed earlier in this conversation. Only
        call this once the user has explicitly confirmed the booking
        summary with "yes".
        """

        booking = context.get("booking") or {}
        customer_id = context.get("customer_id")

        logger.info(
            "session=%s TOOL CALL create_booking(provider_id=%s)",
            session_id, booking.get("provider_id"),
        )

        required = ["provider_id", "service", "city", "date", "description"]
        missing = [f for f in required if not booking.get(f)]

        if missing:
            reason = f"Cannot create booking, missing: {', '.join(missing)}."

            logger.warning(
                "session=%s TOOL create_booking rejected, missing=%s",
                session_id, missing,
            )

            context["booking_rejection_reason"] = reason

            return reason

        try:
            result = BookingTool.create_booking(
                provider_id=booking["provider_id"],
                customer_id=customer_id,
                service=booking["service"],
                city=booking["city"],
                date=booking["date"],
                description=booking["description"],
                auth_token=context.get("auth_token"),
            )
        except Exception as exc:
            logger.exception("session=%s TOOL create_booking failed", session_id)
            context["booking_error"] = str(exc)
            return f"Booking failed: {exc}"

        context["booking_tool_result"] = result

        logger.info("session=%s TOOL RESULT create_booking -> success", session_id)

        return "Booking created successfully."

    @tool("get_booking_status")
    def get_booking_status() -> str:
        """
        Check the live status of the booking created earlier in this
        conversation.
        """

        booking_id = _extract_booking_id(context.get("booking_result"))

        logger.info(
            "session=%s TOOL CALL get_booking_status(booking_id=%s)",
            session_id, booking_id,
        )

        if not booking_id:
            return "No booking exists yet in this conversation."

        result = fetch_booking_status(booking_id)

        if result.get("success"):
            context["booking_status_result"] = result["booking"]
            logger.info("session=%s TOOL RESULT get_booking_status -> found", session_id)
            return "Booking found."

        logger.warning(
            "session=%s TOOL RESULT get_booking_status -> error=%s",
            session_id, result.get("error"),
        )
        return f"Could not retrieve booking: {result.get('error')}"

    return {
        "search_providers": search_providers,
        "recommend_providers": recommend_providers,
        "create_booking": create_booking,
        "get_booking_status": get_booking_status,
    }
