"""
Semantic retrieval over WedaHub's real provider catalogue.

This is the "R" in RAG: given a natural-language query, return the
top-k most semantically relevant real provider records (not text
generated by an LLM) from an in-memory vector index built from actual
provider documents fetched from the Express backend.

=========================================================
Design (kept deliberately simple — see AI service README, "RAG" section)
=========================================================

- Embeddings: fastembed's BAAI/bge-small-en-v1.5 (384-dim, ONNX, no
  PyTorch/GPU needed, ~130MB one-time download, cached locally after
  that). Chosen because it runs fully locally with no extra API key —
  this repo has no embeddings-capable key (Groq does chat completion
  only), and requiring one would make this feature silently unusable
  for anyone without it.
- Index: a plain in-memory NumPy array + cosine similarity. Brute-force
  search over a few hundred providers is sub-millisecond — an actual
  vector database (Qdrant/Pinecone/pgvector) would be solving a scale
  problem this project doesn't have. If the provider catalogue ever
  grows into the tens of thousands, swapping the search in
  _ensure_index()/semantic_search() for a real vector DB is a contained
  change; nothing outside this file needs to know.
- Corpus: every non-blocked provider, fetched via the SAME
  backend_client.search_providers() the rest of the app already uses (called with
  empty service/location, which the existing backend regex-matches as
  "everything" — no new backend endpoint needed). Embedded text is built
  from fields that actually exist on the User model: category,
  description, city, district, rating, reviews (count), name. Review
  *comment* text is not included — pulling it would mean an extra HTTP
  call per provider during indexing for a signal (rating + review count)
  already captured more cheaply from the provider document itself.
- Freshness: the index is built lazily on first use and rebuilt
  automatically once INDEX_TTL_SECONDS has passed, so new/edited
  providers show up within a bounded time with zero manual steps. For
  the "I just changed a bunch of provider data" case, POST /rag/refresh
  (see app/api/rag.py) forces an immediate rebuild.
- Fallback: if fastembed/the model can't load (not installed, or no
  network for the first-time model download) or the provider fetch
  fails, semantic_search() returns None. Callers (app/tools/factory.py)
  are expected to fall back to the existing exact/regex backend_client.search_providers()
  path — retrieval degrades, the chat flow does not break.
"""

import logging
import time

import numpy as np

from app.clients.backend_client import backend_client
from app.core.config import RAG_ENABLED
from app.services.service_categories import normalize_service

logger = logging.getLogger(__name__)

EMBEDDING_MODEL_NAME = "BAAI/bge-small-en-v1.5"
INDEX_TTL_SECONDS = 600  # rebuild automatically after 10 minutes

# Empirically chosen against WedaHub's actual (small) provider catalogue —
# see README "RAG" section for the full calibration notes. Two real
# measurements against the live corpus:
#   - a query the catalogue genuinely has a good match for
#     ("my lights keep flickering...") scored 0.64-0.70 on real electricians
#   - a query for a service the catalogue has NONE of ("Wedding
#     Photography", paired with a made-up city so an exact city-name
#     match can't inflate the score) topped out at 0.50
# 0.55 sits cleanly between those two real measurements. Every provider
# document shares the same templated phrases ("Category: ...", "Located
# in ...", "Rated N from M reviews") — that boilerplate overlap is why a
# single embedding of the whole profile can't be pushed much below ~0.4
# for *any* query, so the threshold has to sit above that floor rather
# than near zero.
MIN_SIMILARITY = 0.55

_EMBEDDER_UNSET = object()
_embedder = _EMBEDDER_UNSET

_index_embeddings = None  # np.ndarray, shape (n_providers, dim)
_index_providers = []  # the real provider dicts, same order as _index_embeddings
_index_built_at = 0.0


def _get_embedder():
    """
    Lazily loads the embedding model exactly once per process. Returns
    None (cached) if it can't be loaded, so every subsequent call fails
    fast instead of retrying a slow/broken import or download.
    """
    global _embedder

    if not RAG_ENABLED:
        return None

    if _embedder is not _EMBEDDER_UNSET:
        return _embedder

    try:
        from fastembed import TextEmbedding

        start = time.perf_counter()
        _embedder = TextEmbedding(model_name=EMBEDDING_MODEL_NAME)
        logger.info(
            "RAG embedder loaded (%s) in %.1fs",
            EMBEDDING_MODEL_NAME,
            time.perf_counter() - start,
        )
    except Exception:
        logger.exception(
            "RAG embedder unavailable — semantic retrieval will fall back "
            "to keyword search until this succeeds (see app/rag/provider_index.py)"
        )
        _embedder = None

    return _embedder


def _provider_text(provider: dict) -> str:
    """
    Builds the text that gets embedded for one provider, from fields
    that actually exist on the User model (see backend/models/user.js):
    firstName/lastName, category, description, city, district, rating,
    reviews (review COUNT, not comment text — see module docstring).
    """
    name = f"{provider.get('firstName', '')} {provider.get('lastName', '')}".strip()
    category = provider.get("category") or ""
    city = provider.get("city") or ""
    district = provider.get("district") or ""
    description = provider.get("description") or ""
    rating = provider.get("rating") or 0
    reviews = provider.get("reviews") or 0

    parts = [
        name,
        f"Category: {category}." if category else "",
        f"Located in {city}, {district} district." if (city or district) else "",
        f"Rated {rating} from {reviews} reviews." if reviews else "No reviews yet.",
        description,
    ]

    return " ".join(p for p in parts if p).strip()


def _fetch_all_providers() -> list[dict]:
    # Empty service/location -> the backend's existing regex match
    # ("" matches every string) returns the full non-blocked provider
    # catalogue. Reuses the exact same call path as normal search.
    return backend_client.search_providers(service="", location="") or []


def _ensure_index(force: bool = False) -> bool:
    """
    Builds the index if it's never been built, rebuilds it if it's
    older than INDEX_TTL_SECONDS, or always rebuilds if force=True.
    Returns True if a usable index exists afterwards.
    """
    global _index_embeddings, _index_providers, _index_built_at

    embedder = _get_embedder()
    if embedder is None:
        return False

    age = time.time() - _index_built_at
    if not force and _index_embeddings is not None and age < INDEX_TTL_SECONDS:
        return True

    try:
        providers = _fetch_all_providers()
    except Exception:
        logger.exception("RAG index build failed — could not fetch providers")
        return _index_embeddings is not None  # keep serving a stale index if we have one

    if not providers:
        logger.warning("RAG index build found zero providers to index")
        _index_embeddings = None
        _index_providers = []
        _index_built_at = time.time()
        return False

    start = time.perf_counter()
    texts = [_provider_text(p) for p in providers]
    embeddings = np.array(list(embedder.embed(texts)))

    _index_embeddings = embeddings
    _index_providers = providers
    _index_built_at = time.time()

    logger.info(
        "RAG index built: %d providers indexed in %.2fs",
        len(providers),
        time.perf_counter() - start,
    )

    return True


def is_available() -> bool:
    return _get_embedder() is not None


def refresh_index() -> dict:
    """Forces an immediate rebuild. Used by POST /rag/refresh."""
    ok = _ensure_index(force=True)
    return {
        "ok": ok,
        "provider_count": len(_index_providers),
        "built_at": _index_built_at,
    }


def index_status() -> dict:
    return {
        "available": is_available(),
        "provider_count": len(_index_providers),
        "built_at": _index_built_at,
        "age_seconds": (time.time() - _index_built_at) if _index_built_at else None,
        "model_name": EMBEDDING_MODEL_NAME,
    }


def semantic_search(query: str, top_k: int = 5, min_similarity: float = MIN_SIMILARITY, service: str | None = None):
    """
    Returns a list of (provider_dict, similarity_score) tuples, most
    relevant first, filtered to similarity >= min_similarity — or None
    if semantic retrieval isn't available at all (caller should fall
    back to keyword search). An empty list is a valid, different
    outcome: retrieval worked but nothing was relevant enough.
    """

    if not query or not query.strip():
        return None

    if not _ensure_index():
        return None

    embedder = _get_embedder()
    query_embedding = np.array(list(embedder.embed([query]))[0])

    norms = np.linalg.norm(_index_embeddings, axis=1) * np.linalg.norm(query_embedding)
    norms[norms == 0] = 1e-9
    similarities = (_index_embeddings @ query_embedding) / norms

    ranked = sorted(
        zip(_index_providers, similarities.tolist()),
        key=lambda pair: pair[1],
        reverse=True,
    )

    requested_service = normalize_service(service)
    results = [
        (provider, score) for provider, score in ranked
        if score >= min_similarity
        and (not requested_service or normalize_service(provider.get("category")) == requested_service)
    ][:top_k]

    logger.info(
        "RAG retrieval query=%r top_k=%d matches=%s",
        query,
        top_k,
        [
            (f"{p.get('firstName', '')} {p.get('lastName', '')}".strip(), round(score, 3))
            for p, score in results
        ],
    )

    return results
